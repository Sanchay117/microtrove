// Copies contract ABIs from the Foundry build into typed TypeScript modules.
// Run `forge build` in ../contracts first, then `npm run abi`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "../contracts/out");
const target = resolve(root, "src/abi");

const contracts = [
  ["Microtroves", "microtrovesAbi"],
  ["MicrotroveVault", "vaultAbi"],
];

mkdirSync(target, { recursive: true });
for (const [name, exportName] of contracts) {
  const { abi } = JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), "utf8"));
  const body = `// Generated by scripts/abi.mjs from contracts/out. Do not edit.\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(resolve(target, `${name}.ts`), body);
  console.log(`wrote src/abi/${name}.ts (${abi.length} entries)`);
}
